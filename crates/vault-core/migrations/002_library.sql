CREATE TABLE IF NOT EXISTS blob_text (sha256 TEXT PRIMARY KEY REFERENCES blobs(sha256), content TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS systems (
  id TEXT PRIMARY KEY, project_id TEXT REFERENCES projects(id) ON DELETE SET NULL, name TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '', install TEXT NOT NULL DEFAULT '', config TEXT NOT NULL DEFAULT '',
  compatibility TEXT NOT NULL DEFAULT '', tests TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'PENDING' CHECK (status IN ('VERIFIED','PARTIALLY VERIFIED','PENDING','FAILED','DEPRECATED')),
  created_at TEXT NOT NULL, updated_at TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS system_members (
  system_id TEXT NOT NULL REFERENCES systems(id) ON DELETE CASCADE, asset_id TEXT NOT NULL REFERENCES assets(id) ON DELETE CASCADE,
  role TEXT NOT NULL DEFAULT '', PRIMARY KEY (system_id, asset_id));
